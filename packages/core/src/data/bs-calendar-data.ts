/**
 * Supported year range
 */
export const BS_YEAR_RANGE = {
  min: 1970,
  max: 2100,
} as const;

/**
 * Get the total days in a BS year
 */
export function getTotalDaysInBsYear(year: number): number {
  const monthDays = BS_MONTH_DAYS[year];
  if (!monthDays) {
    throw new Error(`BS year ${year} is out of supported range (${BS_YEAR_RANGE.min}-${BS_YEAR_RANGE.max})`);
  }
  return monthDays.reduce((sum, days) => sum + days, 0);
}

/**
 * Get days in a specific BS month
 */
export function getDaysInBsMonth(year: number, month: number): number {
  if (month < 1 || month > 12) {
    throw new Error(`Invalid month: ${month}. Month must be between 1 and 12.`);
  }
  const monthDays = BS_MONTH_DAYS[year];
  if (!monthDays) {
    throw new Error(`BS year ${year} is out of supported range (${BS_YEAR_RANGE.min}-${BS_YEAR_RANGE.max})`);
  }
  return monthDays[month - 1];
}

/**
 * Check if a BS year is within the supported range
 */
export function isBsYearSupported(year: number): boolean {
  return year >= BS_YEAR_RANGE.min && year <= BS_YEAR_RANGE.max;
}

/**
 * Convert number to Nepali numerals
 */
export function toNepaliNumeral(num: number): string {
  return num
    .toString()
    .split('')
    .map((digit) => {
      const n = parseInt(digit, 10);
      return isNaN(n) ? digit : NEPALI_DIGITS[n];
    })
    .join('');
}

/**
 * Convert Nepali numerals to number
 */
export function fromNepaliNumeral(str: string): number {
  const converted = str
    .split('')
    .map((char) => {
      const index = NEPALI_DIGITS.indexOf(char as (typeof NEPALI_DIGITS)[number]);
      return index >= 0 ? index.toString() : char;
    })
    .join('');
  return parseInt(converted, 10);
}
